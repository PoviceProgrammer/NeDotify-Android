<# Generate CSS and Kotlin from the same token JSON. -Check never writes files. #>
param(
    [string]$ProjectRoot = (Split-Path $PSScriptRoot -Parent),
    [switch]$Check,
    # Lets fixture checks inspect generator behavior without changing this repo.
    [switch]$CssOnly
)
$ErrorActionPreference = 'Stop'
$ProjectRoot = (Resolve-Path -LiteralPath $ProjectRoot).Path
$source = Join-Path $ProjectRoot 'design/design-tokens.json'
$tokens = Get-Content -LiteralPath $source -Raw | ConvertFrom-Json
if ($tokens.schemaVersion -ne 1) { throw 'Unsupported design token schemaVersion.' }
function Kebab([string]$Name) { return [regex]::Replace($Name, '([a-z0-9])([A-Z])', '$1-$2').ToLowerInvariant() }
function Number([object]$Value, [string]$Name) {
    if ($Value -isnot [ValueType] -or [double]$Value -lt 0 -or [double]$Value -gt 10000 -or [double]$Value % 1 -ne 0) {
        throw "Token '$Name' must be a non-negative integer."
    }
    return ([int]$Value).ToString([Globalization.CultureInfo]::InvariantCulture)
}
$colorNames = @('background','surface','surfaceRaised','onSurface','onSurfaceVariant','primary','onPrimary','outline','error')
$css = [Collections.Generic.List[string]]::new()
$kt = [Collections.Generic.List[string]]::new()
$css.Add('/* Generated by tools/generate-design-tokens.ps1. Edit design/design-tokens.json. */')
$kt.Add('// Generated by tools/generate-design-tokens.ps1. Edit design/design-tokens.json.')
$kt.Add('package ru.nedotify.app.ui.tokens')
$kt.Add('')
$kt.Add('object DesignTokens {')
foreach ($theme in @('dark','light')) {
    $selector = if ($theme -eq 'dark') { ':root, html[data-theme="dark"] {' } else { 'html[data-theme="light"] {' }
    $css.Add($selector)
    $kt.Add("    object $($theme.Substring(0,1).ToUpperInvariant() + $theme.Substring(1)) {")
    $palette = $tokens.colors.$theme
    if (@($palette.PSObject.Properties).Count -ne $colorNames.Count) { throw "Unexpected color keys for $theme." }
    foreach ($name in $colorNames) {
        $value = [string]$palette.$name
        if ($value -cnotmatch '^#[0-9A-F]{6}$') { throw "Color '$theme.$name' must be uppercase #RRGGBB." }
        $css.Add("  --color-$(Kebab $name): $value;")
        $kt.Add("        const val $name`: Long = 0xFF$($value.Substring(1))")
    }
    $css.Add('}')
    $kt.Add('    }')
}
$css.Add(':root {')
foreach ($group in @('spacing','radius','motion','layout')) {
    if (-not $tokens.$group) { throw "Missing token group '$group'." }
    $kt.Add("    object $($group.Substring(0,1).ToUpperInvariant() + $group.Substring(1)) {")
    foreach ($property in $tokens.$group.PSObject.Properties) {
        if ($property.Name -cnotmatch '^[a-z][a-zA-Z0-9]*$') { throw "Invalid token name '$($property.Name)'." }
        $value = Number $property.Value "$group.$($property.Name)"
        $unit = if ($group -eq 'motion') { 'ms' } else { 'px' }
        $css.Add("  --$group-$(Kebab $property.Name): $value$unit;")
        $kt.Add("        const val $($property.Name): Int = $value")
    }
    $kt.Add('    }')
}
if ($tokens.layout.touchTarget -lt 48) { throw 'layout.touchTarget must be at least 48.' }
if ($tokens.layout.railBreakpoint -ge $tokens.layout.paneBreakpoint) { throw 'Adaptive breakpoints must be ordered.' }
$kt.Add('    object Typography {')
foreach ($role in $tokens.typography.PSObject.Properties) {
    if ($role.Name -cnotmatch '^[a-z][a-zA-Z0-9]*$') { throw 'Invalid typography role.' }
    $kt.Add("        object $($role.Name.Substring(0,1).ToUpperInvariant() + $role.Name.Substring(1)) {")
    foreach ($field in @('size','lineHeight','weight')) {
        $value = Number $role.Value.$field "typography.$($role.Name).$field"
        $unit = if ($field -eq 'weight') { '' } else { 'px' }
        $css.Add("  --type-$(Kebab $role.Name)-$(Kebab $field): $value$unit;")
        $kt.Add("            const val $field`: Int = $value")
    }
    if ($role.Value.size -lt 12 -or $role.Value.lineHeight -lt $role.Value.size -or $role.Value.weight -lt 100 -or $role.Value.weight -gt 900) {
        throw "Invalid typography metrics for '$($role.Name)'."
    }
    $kt.Add('        }')
}
$kt.Add('    }')
$kt.Add('}')
$css.Add('}')
$outputs = @([pscustomobject]@{ Path='design/ui-prototype/tokens.css'; Content=($css -join "`n") + "`n" })
if (-not $CssOnly) {
    $outputs += [pscustomobject]@{ Path='app/src/main/java/ru/nedotify/app/ui/tokens/DesignTokens.kt'; Content=($kt -join "`n") + "`n" }
}
foreach ($output in $outputs) {
    $target = Join-Path $ProjectRoot $output.Path
    if ($Check) {
        if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target) -cne $output.Content) {
            throw "Generated token drift: $($output.Path). Run tools/generate-design-tokens.ps1."
        }
    } else {
        [IO.Directory]::CreateDirectory((Split-Path $target -Parent)) | Out-Null
        [IO.File]::WriteAllText($target, $output.Content, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output "Design tokens $(if ($Check) {'verified'} else {'generated'}): $($outputs.Count) output(s)."
